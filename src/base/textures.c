static maage_status base_texture(maage_content_context *context, maage_base_ids *ids, unsigned int slot, unsigned long source, unsigned long fallback, int opaque, unsigned int frame_ticks, int pingpong) {
    maage_texture_definition texture;
    texture.source = source == MAAGE_CONTENT_ID_INVALID ? source : ids->sources[source];
    texture.fallback = fallback == MAAGE_CONTENT_ID_INVALID ? fallback : ids->sources[fallback];
    texture.opaque = opaque;
    texture.frame_ticks = frame_ticks;
    texture.pingpong = pingpong;
    texture.frame_edge = 0;
    return maage_presentation_texture_register(context->presentation, &texture, &ids->textures[slot]);
}
