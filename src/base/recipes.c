/* Pattern symbols are registration-time data only. Every recipe is copied
 * into the same numeric registry before the Server starts. */
static maage_status builtin_recipe(maage_content_context *context, unsigned int kind, unsigned int width, unsigned int height, const char *pattern, const maage_recipe_choice choices[3], maage_item_id output, unsigned int count, maage_item_variant_id variant) {
    const maage_base_ids *ids = (const maage_base_ids *) context->module_data;
    maage_recipe_choice resolved[3];
    maage_recipe_definition recipe;
    unsigned int i, symbol;
    memcpy(resolved, choices, sizeof(resolved));
    for (i = 0; i < 3; ++i)
        if (resolved[i].item == ids->item_planks) {
            resolved[i].kind = MAAGE_RECIPE_CHOICE_TAG;
            resolved[i].tag = ids->tag_planks;
            resolved[i].item = 0;
            resolved[i].variant = MAAGE_RECIPE_VARIANT_ANY;
        }
    memset(&recipe, 0, sizeof(recipe));
    recipe.kind = kind;
    recipe.width = width;
    recipe.height = height;
    recipe.mirror = 1;
    recipe.ingredient_count = width * height;
    recipe.output.item_id = output;
    recipe.output.count = count;
    recipe.output.variant = variant;
    for (i = 0; i < width * height; ++i) {
        if (pattern[i] == ' ') continue;
        symbol = (unsigned int) (pattern[i] - 'A');
        recipe.ingredients[i].choices = &resolved[symbol];
        recipe.ingredients[i].choice_count = 1;
        recipe.ingredients[i].quantity = 1;
    }
    return maage_recipe_registry_register(context->recipes, &recipe, NULL);
}
