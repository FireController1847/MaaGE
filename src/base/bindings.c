static maage_status base_bind_drop(maage_content_context *context, maage_block_id block_id, maage_item_id item_id) {
    const maage_block_definition *registered = maage_block_registry_block(context->blocks, block_id);
    maage_block_definition block;
    if (!registered || !maage_item_registry_get(context->items, item_id)) return maage_status_make(MAAGE_STATUS_NOT_FOUND, MAAGE_CONTEXT_REGISTRY, MAAGE_OPERATION_RESOLVE, 0);
    block = *registered;
    block.drop_item_id = item_id;
    return maage_block_registry_update_block(context->blocks, &block);
}

