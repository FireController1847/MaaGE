typedef struct base_sound_family {
    maage_sound_resource_id *resources;
    size_t count;
} base_sound_family;
/* Numbered files are one content family's variations. Independent families,
 * material definitions, events and tracks remain explicit registration sites. */
static maage_status base_sound_family_register(maage_content_context *context, const char *name, const char *stem, unsigned int first, unsigned int count, base_sound_family *family) {
    maage_sound_resource_definition resource;
    maage_status result;
    char path[160], identity[160];
    unsigned int i;
    family->resources = (maage_sound_resource_id *) malloc((size_t) count * sizeof(*family->resources));
    if (!family->resources) return maage_status_make(MAAGE_STATUS_ALLOCATION_FAILED, MAAGE_CONTEXT_REGISTRY, MAAGE_OPERATION_REGISTER, 0);
    family->count = count;
    for (i = 0; i < count; ++i) {
        sprintf(identity, "%s/%u", name, i + 1);
        if (!first && !i) sprintf(path, "minecraft/sounds/%s.ogg", stem);
        else sprintf(path, "minecraft/sounds/%s%u.ogg", stem, first ? first + i : i + 1);
        memset(&resource, 0, sizeof(resource));
        resource.path = path;
        result = maage_sound_resource_register(context->sounds, identity, &resource);
        if (maage_status_failed(result)) return result;
        family->resources[i] = resource.id;
    }
    return maage_status_make(MAAGE_STATUS_SUCCESS, 0, MAAGE_OPERATION_REGISTER, 0);
}
static maage_status base_sound_event(maage_content_context *context, const char *name, const base_sound_family *family, unsigned int bus, int positional, float gain, float pitch, maage_sound_id *id) {
    maage_sound_definition definition;
    maage_status result;
    memset(&definition, 0, sizeof(definition));
    definition.resources = family ? family->resources : NULL;
    definition.resource_count = family ? family->count : 0;
    definition.bus = bus;
    definition.positional = positional;
    definition.gain = gain;
    definition.pitch = pitch;
    definition.distance = 16;
    result = maage_sound_register(context->sounds, name, &definition);
    if (!maage_status_failed(result)) *id = definition.id;
    return result;
}
static maage_status base_material_event(maage_content_context *context, const char *material, const char *action, const base_sound_family *family, unsigned int bus, float gain, float pitch, maage_sound_id *id) {
    char name[160];
    if (!family) {
        *id = 0;
        return maage_status_make(MAAGE_STATUS_SUCCESS, 0, MAAGE_OPERATION_REGISTER, 0);
    }
    sprintf(name, "%s/%s", material, action);
    return base_sound_event(context, name, family, bus, 1, gain, pitch, id);
}
static maage_status base_sound_material(maage_content_context *context, const char *name, const maage_sound_bindings *defaults, const base_sound_family *step, const base_sound_family *broken, const base_sound_family *placed, float volume, float pitch, maage_sound_material_id *id) {
    maage_sound_material_definition material;
    maage_status result;
    memset(&material, 0, sizeof(material));
    memcpy(material.actions, defaults->actions, sizeof(material.actions));
    result = base_material_event(context, name, "step", step, MAAGE_SOUND_BUS_PLAYERS, 0.15f * volume, pitch, &material.actions[MAAGE_SOUND_FOOTSTEP]);
    if (!maage_status_failed(result)) result = base_material_event(context, name, "break", broken, MAAGE_SOUND_BUS_BLOCKS, (volume + 1) * 0.5f, 0.8f * pitch, &material.actions[MAAGE_SOUND_BLOCK_BREAK]);
    if (!maage_status_failed(result)) result = base_material_event(context, name, "place", placed, MAAGE_SOUND_BUS_BLOCKS, (volume + 1) * 0.5f, 0.8f * pitch, &material.actions[MAAGE_SOUND_BLOCK_PLACE]);
    if (!maage_status_failed(result)) result = base_material_event(context, name, "dig", step, MAAGE_SOUND_BUS_BLOCKS, (volume + 1) * 0.125f, 0.5f * pitch, &material.actions[MAAGE_SOUND_BLOCK_DIG]);
    if (!maage_status_failed(result)) result = base_material_event(context, name, "land", step, MAAGE_SOUND_BUS_PLAYERS, 0.5f * volume, 0.75f * pitch, &material.actions[MAAGE_SOUND_PLAYER_LAND]);
    if (!maage_status_failed(result)) result = maage_sound_material_register(context->sounds, name, &material);
    if (!maage_status_failed(result)) *id = material.id;
    return result;
}
static maage_status base_music_resource(maage_content_context *context, const char *name, const char *path, maage_sound_resource_id *id) {
    maage_sound_resource_definition resource;
    maage_status result;
    memset(&resource, 0, sizeof(resource));
    resource.path = path;
    resource.streamed = 1;
    result = maage_sound_resource_register(context->sounds, name, &resource);
    if (!maage_status_failed(result)) *id = resource.id;
    return result;
}
static maage_sound_music_id base_music_select(const void *context, const maage_sound_scene_query *query) {
    const maage_base_sound_data *data = (const maage_base_sound_data *) context;
    return !query->has_world ? data->menu_music : (query->game_mode == MAAGE_GAME_MODE_CREATIVE ? data->creative_music : data->game_music);
}
